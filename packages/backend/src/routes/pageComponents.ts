import { isPageComponent } from '@nordcraft/core'
import {
  processComponentApis,
  resolveClasses,
  takeIncludedComponents,
  urlWithCacheBuster,
} from '@nordcraft/ssr'
import type { Handler } from 'hono'
import type { HonoEnv, HonoProject } from '../../hono'
import type { PageLoader, PageLoaderUrls } from '../loaders/types'

const ONE_YEAR_SECONDS = 60 * 60 * 24 * 365

export const pageComponentsUrl = (pageName: string) =>
  `/.nordcraft/components/${encodeURIComponent(pageName)}.js`

export const pageComponentsHandler =
  ({
    pageLoader,
    urls,
    cacheBuster,
  }: {
    pageLoader: PageLoader
    urls: PageLoaderUrls
    cacheBuster?: string
  }): Handler<
    HonoEnv<Partial<HonoProject>>,
    '/.nordcraft/components/:pageName{.+.js}'
  > =>
  async (ctx) => {
    let pageName = ctx.req.param('pageName')
    if (pageName.endsWith('.js')) {
      pageName = pageName.slice(0, -'.js'.length)
    }

    const files = await pageLoader({ ctx, name: pageName })
    const _page = files?.components?.[pageName]
    if (!files || !_page || !isPageComponent(_page)) {
      return ctx.body(null, 404)
    }

    const page = processComponentApis(_page, files)
    const includedComponents = takeIncludedComponents({
      root: page,
      projectComponents: files.components,
      packages: files.packages,
      includeRoot: false,
    }).map((component) => processComponentApis(component, files))

    const resolvedPage = resolveClasses()(page)
    const resolvedIncludedComponents = includedComponents.map(resolveClasses())

    const project = ctx.var.project?.short_id
    if (typeof project !== 'string') {
      return ctx.body(null, 500)
    }

    const usesCustomCode = Boolean(files.customCode)
    const customCodeUrl = usesCustomCode
      ? urlWithCacheBuster(urls.customCodeUrl(pageName), cacheBuster)
      : undefined

    const js = `\
// This file is auto-generated by nordcraft. Do not edit directly.
import { hydratePage } from '/_static/page.main.esm.js';
${
  usesCustomCode
    ? `import { loadCustomCode, formulas, actions } from '${customCodeUrl}';\n`
    : ''
}const component = ${JSON.stringify(resolvedPage)};
const components = ${JSON.stringify(resolvedIncludedComponents)};
hydratePage({
  project: ${JSON.stringify(project)},
  branch: "main",
  commit: "unknown",
  component,
  components,${
    usesCustomCode ? '\n  formulas,\n  actions,\n  loadCustomCode,' : ''
  }
});
`

    const requestCacheBuster = new URL(ctx.req.url).searchParams.get('v')
    const isImmutableCacheHit =
      typeof cacheBuster === 'string' && requestCacheBuster === cacheBuster

    ctx.header('Content-Type', 'application/javascript')
    ctx.header(
      'Cache-Control',
      isImmutableCacheHit
        ? `public, max-age=${ONE_YEAR_SECONDS}, immutable`
        : 'no-cache',
    )
    return ctx.body(js)
  }
