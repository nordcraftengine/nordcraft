import { describe, expect, test } from 'bun:test'
import { escapeAttrValue, toEncodedText } from './attributes'

describe('toEncodedText', () => {
  test('returns plain text unchanged', () => {
    expect(toEncodedText('Hello world')).toBe('Hello world')
  })

  test('escapes all occurrences of special characters and newlines', () => {
    expect(
      toEncodedText('<div>"Hello" & \'world\'\nLine 2\nLine 3</div>'),
    ).toBe(
      '&lt;div&gt;&quot;Hello&quot; &amp; &#39;world&#39;<br />Line 2<br />Line 3&lt;/div&gt;',
    )
  })

  test('does not double-escape ampersands generated by escaping', () => {
    expect(toEncodedText('< & >')).toBe('&lt; &amp; &gt;')
  })
})

describe('escapeAttrValue', () => {
  test('returns empty string for nullish or non-primitive values', () => {
    expect(escapeAttrValue(undefined)).toBe('')
    expect(escapeAttrValue(null)).toBe('')
    expect(escapeAttrValue({})).toBe('')
  })

  test('returns plain strings and primitive values without escaping when no special characters exist', () => {
    expect(escapeAttrValue('simple-class')).toBe('simple-class')
    expect(escapeAttrValue(42)).toBe('42')
    expect(escapeAttrValue(true)).toBe('true')
  })

  test('escapes all quotes and angle brackets in attribute values', () => {
    expect(escapeAttrValue('a "quoted" <value> & more "quotes"')).toBe(
      'a &quot;quoted&quot; &lt;value&gt; & more &quot;quotes&quot;',
    )
  })
})
